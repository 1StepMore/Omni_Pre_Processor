#!/usr/bin/env python3
"""doc_inventory — OPP 文档真值门禁（issue OPP#111）。

从源码派生「活体数字」（MCP 工具数、输入格式数、场景数、版本），
与 README/AGENTS/docs 中的声明比对；生成 docs/dev/doc-inventory.md
文档行集，并做引用路径完整性检查。

用法：
    python scripts/doc_inventory.py            # 重新生成 docs/dev/doc-inventory.md
    python scripts/doc_inventory.py --check    # 校验模式：exit 0 = 干净，1 = 有漂移

设计原则（与套件仓 scripts/doc_inventory.py 同源，右尺寸版）：
- 声明必须能被源码派生值证伪；派生不到的数字不要写进文档。
- 本文件只依赖标准库（yaml 场景计数用行级正则，不引 PyYAML）。
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

AUTO_HEADER = "<!-- AUTO-GENERATED by scripts/doc_inventory.py — do not edit by hand. -->"
INVENTORY_PATH = ROOT / "docs" / "dev" / "doc-inventory.md"

# ── 派生源（活体） ──────────────────────────────────────────────────────────


def _derive_tools() -> tuple[int, list[str]]:
    """MCP 工具名与数量：server 的 _TOOL_SCHEMAS 是唯一权威。"""
    from opp.mcp.server import _TOOL_SCHEMAS

    names = [str(s.get("name")) for s in _TOOL_SCHEMAS]
    return len(names), names


def _derive_input_formats() -> tuple[int, list[str]]:
    """输入格式：get_capabilities 的运行时声明列表。"""
    from opp.mcp.tools.get_capabilities import _INPUT_FORMATS

    return len(_INPUT_FORMATS), list(_INPUT_FORMATS)


def _derive_extractors() -> int:
    """extractors 注册表类数（不含基类）。"""
    from opp.extractors import __all__ as registry

    return len([n for n in registry if n != "ExtractorBase"])


def _derive_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data["project"]["version"])


def _derive_scenarios() -> tuple[int, dict[str, int]]:
    """scenarios/**/*.yaml 计数 + tier 拆分（行级正则，跳过 dot 目录）。

    与套件仓 scripts/validation/scenario_discovery.py 同一规则；此处不引
    PyYAML，tier 用首行 `tier:` 正则提取（缺省 tier 1）。
    """
    scenarios = ROOT / "scenarios"
    if not scenarios.is_dir():
        return 0, {}
    yamls = sorted(
        p
        for p in scenarios.rglob("*.yaml")
        if p.is_file() and not any(part.startswith(".") for part in p.parts)
    )
    tiers: dict[str, int] = {}
    for p in yamls:
        tier = "1"
        for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if re.match(r"tier\s*:", line.strip()):
                tier = line.split(":", 1)[1].strip()
                break
        tiers[tier] = tiers.get(tier, 0) + 1
    return len(yamls), tiers


# ── 声明点（要被门禁的文档数字） ────────────────────────────────────────────

#: (文件, 编译好的正则, 组号 -> 槽位, 槽位取值函数)。
#: 槽位取值函数返回该声明应当等于的派生值。
_TOOL_COUNT = lambda: _derive_tools()[0]  # noqa: E731
_FORMAT_COUNT = lambda: _derive_input_formats()[0]
_SCENARIO_COUNT = lambda: _derive_scenarios()[0]

_CLAIM_SITES: tuple[tuple[str, re.Pattern[str], int, object], ...] = (
    ("README.md", re.compile(r"(\d+)\s+input formats"), 1, _FORMAT_COUNT),
    ("AGENTS.md", re.compile(r"(\d+)\s+input formats"), 1, _FORMAT_COUNT),
    ("AGENTS.md", re.compile(r"MCP tools \((\d+) total\)"), 1, _TOOL_COUNT),
    ("AGENTS.md", re.compile(r"Supports all (\d+) input formats"), 1, _FORMAT_COUNT),
    ("README.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
    ("AGENTS.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
)

#: 反引号引用路径做存在性检查的文件（引用完整性）。
#: docs/API.md 刻意不在列——它描述 OOXML zip 内部布局（word/numbering.xml
#: 之类），那些「路径」永远不存在于仓库，属于伪路径文档。
REFERENTIAL_SCOPE = ("README.md", "AGENTS.md")
_PATH_TOKEN_RE = re.compile(r"`([^`\n]+)`")


def _check_claims(failures: list[str]) -> None:
    for rel, pattern, group, derive in _CLAIM_SITES:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        expected = derive()  # type: ignore[operator]
        for m in pattern.finditer(text):
            claimed = int(m.group(group))
            if claimed != expected:
                failures.append(
                    f"{rel}: claims {m.group(0)!r} but the source derives "
                    f"{expected} — update the doc when the surface changes"
                )


_PATH_CHARS = " \t."
_PATH_SUFFIXES = (
    ".md", ".py", ".yaml", ".yml", ".toml", ".sh", ".json", ".txt",
    ".docx", ".pptx", ".pdf", ".html", ".xml", ".csv",
)
#: 仓库相对路径的合法顶层锚点：不以此开头的 token（``index.html``、
#: ``xliff_map.json`` 等）是产物/zip 内部名，不是仓库路径，不做检查。
_PATH_ANCHORS = (
    "tests/", "docs/", "scripts/", "src/", "scenarios/", ".opencode/",
    "examples/", "Omni_", "README.md", "AGENTS.md", "CHANGELOG.md",
    "CONTRIBUTING.md", "pyproject.toml", ".pre-commit-config.yaml",
)


def _looks_like_repo_path(token: str) -> bool:
    """反引号 token 是否像仓库相对路径：以顶层锚点开头。

    API 文档里的类名、产物名（``index.html``、``xliff_map.json``）、
    裸后缀（``.md``）都不满足，避免误报。
    """
    if not token.startswith(_PATH_ANCHORS):
        return False
    token = token.split(":", 1)[0]  # ``path.py:62`` / ``path.py:Symbol`` 行/符号引用
    base = token.rsplit("/", 1)[-1]
    if not base.split(".")[0]:
        return False  # 裸后缀：最后一个点前没有 stem，不是路径
    return not any(c in token for c in '*{}<> "\\')


def _check_referential_paths(failures: list[str]) -> None:
    """反引号里的路径必须在本仓或父仓（suite）解析。

    子仓 AGENTS.md 引用 suite 的 docs（如 docs/dev/*.md）是合法跨仓引用，
    按父仓根解析；两边都解析不到才算失败。
    """
    _skip_prefixes = ("http://", "https://", "/", "~", "pip ", "python ", "uv ")
    for rel in REFERENTIAL_SCOPE:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in _PATH_TOKEN_RE.finditer(text):
            token = m.group(1).strip()
            if not _looks_like_repo_path(token):
                continue
            if any(token.startswith(p) for p in _skip_prefixes):
                continue
            token = token.split(":", 1)[0]  # ``path.py:62`` 行/符号引用
            # 本仓 / 父仓（suite docs）/ 兄弟子仓（AGENTS 引用 OL/ORF 源码
            # 属合法跨仓引用，按兄弟仓根解析）。
            bases = (ROOT, ROOT.parent,
                     ROOT.parent / "Omni_Localizer", ROOT.parent / "Omni_Re_Formatter")
            if any((base / token).exists() for base in bases):
                continue
            failures.append(f"{rel}: backticked path does not exist: {token!r}")


# ── 行集生成 ────────────────────────────────────────────────────────────────


def _doc_rows() -> list[tuple[str, int]]:
    rows = []
    docs = ROOT / "docs"
    for p in sorted(docs.rglob("*.md")):
        if "dev/doc-inventory" in p.as_posix():
            continue
        lines = len(p.read_text(encoding="utf-8", errors="replace").splitlines())
        rows.append((p.as_posix(), lines))
    for rel in ("README.md", "AGENTS.md"):
        p = ROOT / rel
        if p.is_file():
            rows.append((rel, len(p.read_text(encoding="utf-8", errors="replace").splitlines())))
    rows.sort()
    return rows


def generate() -> str:
    tools, tool_names = _derive_tools()
    fmts, fmt_names = _derive_input_formats()
    extractors = _derive_extractors()
    version = _derive_version()
    scenarios, tiers = _derive_scenarios()

    lines = [
        AUTO_HEADER,
        "",
        "# OPP doc inventory",
        "",
        f"- Generated by `scripts/doc_inventory.py`; verify with `--check`.",
        f"- Source-derived: version **{version}** · MCP tools **{tools}** "
        f"({', '.join(tool_names)}) · input formats **{fmts}** · "
        f"extractor classes **{extractors}** · scenarios **{scenarios}** "
        f"(tiers={dict(sorted(tiers.items()))})",
        "",
        "| Document | Lines |",
        "|---|---:|",
    ]
    lines += [f"| {rel} | {n} |" for rel, n in _doc_rows()]
    lines.append("")
    return "\n".join(lines)


def check() -> int:
    failures: list[str] = []
    _check_claims(failures)
    _check_referential_paths(failures)

    # 行集新鲜度：重新生成必须与在盘文件逐字节一致
    if INVENTORY_PATH.is_file():
        on_disk = INVENTORY_PATH.read_text(encoding="utf-8")
        if on_disk != generate():
            failures.append(
                "docs/dev/doc-inventory.md is stale — run "
                "`python scripts/doc_inventory.py` to regenerate"
            )
    else:
        failures.append("docs/dev/doc-inventory.md missing — run scripts/doc_inventory.py")

    if failures:
        print("check FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("check passed: claims match source-derived values, paths resolve, inventory fresh.")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="doc_inventory")
    ap.add_argument("--check", action="store_true", help="verify instead of generate")
    args = ap.parse_args(argv)
    if args.check:
        return check()
    INVENTORY_PATH.parent.mkdir(parents=True, exist_ok=True)
    INVENTORY_PATH.write_text(generate(), encoding="utf-8")
    print(f"Wrote {INVENTORY_PATH} ({len(_doc_rows())} rows).")
    print("Regenerate after doc changes; verify with --check (exit 0 = clean).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
