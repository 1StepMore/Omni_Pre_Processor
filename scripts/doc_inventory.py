#!/usr/bin/env python3
"""doc_inventory — OPP 文档真值门禁（issue OPP#111）。

从源码派生「活体数字」（MCP 工具数、输入格式数、场景数、版本），
与 README/AGENTS/docs 中的声明比对；生成 docs/dev/doc-inventory.md
文档行集，并做引用路径完整性检查。

用法：
    python scripts/doc_inventory.py            # 重新生成 docs/dev/doc-inventory.md
    python scripts/doc_inventory.py --check    # 校验模式：exit 0 = 干净，1 = 有漂移

设计原则（与套件仓 scripts/doc_inventory.py 同源，右尺寸版）：
- 声明必须能被源码派生值证伪；派生不到的数字不要写进文档。
- 本文件只依赖标准库（yaml 场景计数用行级正则，不引 PyYAML）。
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

AUTO_HEADER = "<!-- AUTO-GENERATED by scripts/doc_inventory.py — do not edit by hand. -->"
INVENTORY_PATH = ROOT / "docs" / "dev" / "doc-inventory.md"

#: Pinned SHA-256 of the cross-repo documentation-architecture playbook copy.
#: All six participating repositories hold this file byte-identical (canonical
#: copy: AutoInfo); an edit is a six-repo sync plus six pin bumps. Deliberately
#: NOT wired into the cross-repo resolution block — this check is pure local
#: (OPP#120; protocol: e2e-test-suite#254).
DOC_ARCH_SHA256 = "725316a1fd83fcf68243ab87144f37add67b45275bd5faa31883c2f0bb061807"
_DOC_ARCH = ROOT / "docs" / "dev" / "agent-era-doc-architecture.md"

# ── 派生源（活体） ──────────────────────────────────────────────────────────


def _derive_tools() -> tuple[int, list[str]]:
    """MCP 工具名与数量：server 的 _TOOL_SCHEMAS 是唯一权威。"""
    from opp.mcp.server import _TOOL_SCHEMAS

    names = [str(s.get("name")) for s in _TOOL_SCHEMAS]
    return len(names), names


def _derive_input_formats() -> tuple[int, list[str]]:
    """输入格式：get_capabilities 的运行时声明列表。"""
    from opp.mcp.tools.get_capabilities import _INPUT_FORMATS

    return len(_INPUT_FORMATS), list(_INPUT_FORMATS)


def _derive_extractors() -> int:
    """extractors 注册表类数（不含基类）。"""
    from opp.extractors import __all__ as registry

    return len([n for n in registry if n != "ExtractorBase"])


def _derive_version() -> str:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data["project"]["version"])


def _derive_scenarios() -> tuple[int, dict[str, int]]:
    """scenarios/**/*.yaml 计数 + tier 拆分（行级正则，跳过 dot 目录）。

    与套件仓 scripts/validation/scenario_discovery.py 同一规则；此处不引
    PyYAML，tier 用首行 `tier:` 正则提取（缺省 tier 1）。
    """
    scenarios = ROOT / "scenarios"
    if not scenarios.is_dir():
        return 0, {}
    yamls = sorted(
        p
        for p in scenarios.rglob("*.yaml")
        if p.is_file() and not any(part.startswith(".") for part in p.parts)
    )
    tiers: dict[str, int] = {}
    for p in yamls:
        tier = "1"
        for line in p.read_text(encoding="utf-8", errors="replace").splitlines():
            if re.match(r"tier\s*:", line.strip()):
                tier = line.split(":", 1)[1].strip()
                break
        tiers[tier] = tiers.get(tier, 0) + 1
    return len(yamls), tiers


# ── 声明点（要被门禁的文档数字） ────────────────────────────────────────────

#: (文件, 编译好的正则, 组号 -> 槽位, 槽位取值函数)。
#: 槽位取值函数返回该声明应当等于的派生值。
_TOOL_COUNT = lambda: _derive_tools()[0]  # noqa: E731
_FORMAT_COUNT = lambda: _derive_input_formats()[0]
_SCENARIO_COUNT = lambda: _derive_scenarios()[0]

_CLAIM_SITES: tuple[tuple[str, re.Pattern[str], int, object], ...] = (
    ("README.md", re.compile(r"(\d+)\s+input formats"), 1, _FORMAT_COUNT),
    ("AGENTS.md", re.compile(r"(\d+)\s+input formats"), 1, _FORMAT_COUNT),
    ("AGENTS.md", re.compile(r"MCP tools \((\d+) total\)"), 1, _TOOL_COUNT),
    ("AGENTS.md", re.compile(r"Supports all (\d+) input formats"), 1, _FORMAT_COUNT),
    ("README.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
    ("AGENTS.md", re.compile(r"(\d+) validation scenarios"), 1, _SCENARIO_COUNT),
)

#: 反引号引用路径做存在性检查的文件（引用完整性）。
#: docs/API.md 刻意不在列——它描述 OOXML zip 内部布局（word/numbering.xml
#: 之类），那些「路径」永远不存在于仓库，属于伪路径文档。
REFERENTIAL_SCOPE = ("README.md", "AGENTS.md")
_PATH_TOKEN_RE = re.compile(r"`([^`\n]+)`")


def _check_claims(failures: list[str]) -> None:
    for rel, pattern, group, derive in _CLAIM_SITES:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        expected = derive()  # type: ignore[operator]
        for m in pattern.finditer(text):
            claimed = int(m.group(group))
            if claimed != expected:
                failures.append(
                    f"{rel}: claims {m.group(0)!r} but the source derives "
                    f"{expected} — update the doc when the surface changes"
                )


_PATH_CHARS = " \t."
_PATH_SUFFIXES = (
    ".md", ".py", ".yaml", ".yml", ".toml", ".sh", ".json", ".txt",
    ".docx", ".pptx", ".pdf", ".html", ".xml", ".csv",
)
#: 仓库相对路径的合法顶层锚点：不以此开头的 token（``index.html``、
#: ``xliff_map.json`` 等）是产物/zip 内部名，不是仓库路径，不做检查。
_PATH_ANCHORS = (
    "tests/", "docs/", "scripts/", "src/", "scenarios/", ".opencode/",
    "examples/", "Omni_", "README.md", "AGENTS.md", "CHANGELOG.md",
    "CONTRIBUTING.md", "pyproject.toml", ".pre-commit-config.yaml",
)


# ── BEGIN SHARED CROSS-REPO RESOLUTION (e2e-test-suite#253) ──────────────────
# Byte-identical in Omni_Localizer / Omni_Pre_Processor / Omni_Re_Formatter.
# Edit all three together; tests/test_doc_inventory_copy_parity.py in the
# suite repo fails when the copies drift.
#
# A backticked path with no repo prefix is a path in THIS repo and must
# exist. A prefixed token -- ``suite:docs/dev/x.md``, ``ol:src/ol_md/y.py``,
# ``opp:src/opp/z.py``, ``orf:tests/w.py`` -- names the owning repo. A
# prefixed token is verifiable only when that checkout is present; without
# it the reference is counted as skipped (never silently treated as valid)
# and the final message says so.

_CROSS_REPO_MARKERS: dict[str, tuple[str, ...]] = {
    "suite": ("omni_suite", "omni_mcp"),
    "opp": ("src/opp",),
    "ol": ("src/ol_md",),
    "orf": ("src/orf",),
}
_CROSS_REPO_DIRNAMES: dict[str, tuple[str, ...]] = {
    "suite": ("", "e2e-test-suite", "suite"),
    "opp": ("Omni_Pre_Processor",),
    "ol": ("Omni_Localizer",),
    "orf": ("Omni_Re_Formatter",),
}
_CROSS_REPO_PREFIXES = tuple(sorted(_CROSS_REPO_MARKERS))
_SKIP_PREFIXES = ("http://", "https://", "/", "~", "pip ", "python ", "uv ")


def _split_repo_prefix(token: str) -> tuple[str | None, str]:
    """``suite:docs/x.md`` -> ``("suite", "docs/x.md")``; unprefixed is local."""
    for repo in _CROSS_REPO_PREFIXES:
        head = repo + ":"
        if token.startswith(head):
            return repo, token[len(head):]
    return None, token


def _looks_like_repo_path(token: str) -> bool:
    """反引号 token 是否像仓库相对路径（可有跨仓前缀，以顶层锚点开头）。

    类名、产物名（zip 内部文件 / OOXML 布局）、裸后缀（``.md``）都不满足，
    避免误报。
    """
    _, path = _split_repo_prefix(token)
    if not path.startswith(_PATH_ANCHORS):
        return False
    base = path.rsplit("/", 1)[-1]
    if not base.split(".")[0]:
        return False  # 裸后缀：最后一个点前没有 stem，不是路径
    return not any(c in path for c in '*{}<> "\\')


def _env_cross_roots(root: Path) -> list[Path]:
    """Candidate checkouts, highest priority first.

    ``DOC_CROSS_ROOT`` (``os.pathsep``-separated) wins so CI can point at the
    sibling checkout explicitly; then the conventional layouts -- a sibling of
    this repo, ``../e2e-test-suite``, ``../suite``.
    """
    bases: list[Path] = []
    for part in os.environ.get("DOC_CROSS_ROOT", "").split(os.pathsep):
        part = part.strip()
        if part and Path(part) not in bases:
            bases.append(Path(part))
    for base in (root.parent, root.parent / "e2e-test-suite", root.parent / "suite"):
        if base not in bases:
            bases.append(base)
    return bases


def _is_checkout(repo: str, path: Path) -> bool:
    return path.is_dir() and any((path / marker).exists()
                                 for marker in _CROSS_REPO_MARKERS[repo])


def _resolve_cross_roots(root: Path) -> dict[str, Path]:
    """Resolve every known repo to a real checkout, including this one.

    Absent repos are left out of the mapping -- a single-repo CI checkout
    legitimately cannot verify them, so their references are reported as
    skipped rather than passed or failed.
    """
    resolved: dict[str, Path] = {}
    for repo, markers in _CROSS_REPO_MARKERS.items():
        if any((root / marker).exists() for marker in markers):
            resolved[repo] = root
            break
    for repo, dirnames in _CROSS_REPO_DIRNAMES.items():
        if repo in resolved:
            continue
        for base in _env_cross_roots(root):
            for dirname in dirnames:
                cand = base / dirname if dirname else base
                if _is_checkout(repo, cand):
                    resolved[repo] = cand
                    break
            if repo in resolved:
                break
    return resolved


def _check_referential_paths(failures: list[str]) -> dict[str, int]:
    """Backticked paths: local ones must exist; prefixed ones need their repo.

    Returns the per-repo count of prefixed references that could not be
    verified because that checkout is absent (``{"ol": 2}`` etc.).
    """
    roots = _resolve_cross_roots(ROOT)
    skipped: dict[str, int] = {}
    for rel in REFERENTIAL_SCOPE:
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in _PATH_TOKEN_RE.finditer(text):
            token = m.group(1).strip()
            if not token or token.startswith(_SKIP_PREFIXES):
                continue
            repo, raw_path = _split_repo_prefix(token)
            if not _looks_like_repo_path(token):
                continue
            target = raw_path.split(":", 1)[0]  # ``path.py:62`` / ``path.py::test``
            if not target:
                continue
            if repo is None:
                if not (ROOT / target).exists():
                    failures.append(
                        f"{rel}: backticked path does not exist: {token!r} "
                        "(this repo)"
                    )
                continue
            base = roots.get(repo)
            if base is None:
                skipped[repo] = skipped.get(repo, 0) + 1
                continue
            if not (base / target).exists():
                failures.append(
                    f"{rel}: backticked path does not exist: {token!r} "
                    f"(repo {repo!r} resolved at {base})"
                )
    return skipped
# ── END SHARED CROSS-REPO RESOLUTION (e2e-test-suite#253) ────────────────────

# ── BEGIN SHARED GOVERNANCE CHECKS (agent-governance 2026-11-08) ─────────────
# Byte-identical in all four copies (suite + OPP/OL/ORF); parity is enforced by
# the suite test tests/test_doc_inventory_copy_parity.py. Change rule: edit
# every checked-out copy byte for byte, then re-run each repo's --check gate.
# Each copy's call site passes its own scope OUTSIDE this block so the block
# itself needs no per-repo knowledge.
GOV_AGENTS_LINE_CAP = 200
GOV_ROLE_LINE_CAP = 30
GOV_ROLE_SECTIONS = (
    "## Done",
    "## 返回格式",
    "## 工具与来源指引",
    "## 任务边界与禁止触碰",
    "## Stop & Escalate",
)
_GOV_PLACEHOLDER_RE = re.compile(r"(?<!\$)\{\{[^{}]{1,120}\}\}")
_GOV_ANCHOR_DEF_RE = re.compile(r"\{#([A-Za-z0-9_-]+)\}")
_GOV_ANCHOR_REF_RE = re.compile(r"#([A-Za-z0-9_-]+)")


def gov_agents_line_cap(root: Path, failures: list[str]) -> None:
    """C3: the repo root AGENTS.md must stay within the line cap."""
    path = root / "AGENTS.md"
    if not path.is_file():
        return
    count = len(path.read_text(encoding="utf-8").splitlines())
    if count > GOV_AGENTS_LINE_CAP:
        failures.append(f"AGENTS.md: {count} lines > cap {GOV_AGENTS_LINE_CAP} (C3)")


def gov_no_placeholders(root: Path, rel: str, failures: list[str]) -> None:
    """C5: backfilled files must not carry leftover {{placeholder}} tokens."""
    path = root / rel
    if not path.is_file():
        return
    for lineno, line in enumerate(
        path.read_text(encoding="utf-8").splitlines(), start=1
    ):
        match = _GOV_PLACEHOLDER_RE.search(line)
        if match:
            failures.append(
                f"{rel}:{lineno}: leftover placeholder {match.group(0)} (C5)"
            )


def gov_role_contracts(root: Path, failures: list[str]) -> None:
    """C4: each .agents/roles/*.md carries every required section with a
    non-empty body, within the line cap. Pointer-model repos without the
    directory skip silently."""
    roles_dir = root / ".agents" / "roles"
    if not roles_dir.is_dir():
        return
    for path in sorted(roles_dir.glob("*.md")):
        if path.name.lower() == "readme.md":
            continue
        rel = path.relative_to(root).as_posix()
        lines = path.read_text(encoding="utf-8").splitlines()
        if len(lines) > GOV_ROLE_LINE_CAP:
            failures.append(
                f"{rel}: {len(lines)} lines > cap {GOV_ROLE_LINE_CAP} (C4)"
            )
        for heading in GOV_ROLE_SECTIONS:
            start = next(
                (
                    i
                    for i, line in enumerate(lines)
                    if line.strip().startswith(heading)
                ),
                None,
            )
            if start is None:
                failures.append(f"{rel}: missing required section `{heading}` (C4)")
                continue
            body: list[str] = []
            for line in lines[start + 1:]:
                if line.strip().startswith("## "):
                    break
                if line.strip():
                    body.append(line)
            if not body:
                failures.append(f"{rel}: empty section `{heading}` (C4)")


def gov_expectations_mapping(root: Path, failures: list[str]) -> None:
    """C7: .agents/expectations/INDEX.md anchor references must resolve in
    scenarios/STANDARDS.md. Repos without the mapping layer skip silently."""
    index = root / ".agents" / "expectations" / "INDEX.md"
    standards = root / "scenarios" / "STANDARDS.md"
    if not index.is_file():
        return
    if not standards.is_file():
        failures.append(
            ".agents/expectations/INDEX.md: scenarios/STANDARDS.md missing (C7)"
        )
        return
    anchors = set(_GOV_ANCHOR_DEF_RE.findall(standards.read_text(encoding="utf-8")))
    for lineno, line in enumerate(
        index.read_text(encoding="utf-8").splitlines(), start=1
    ):
        if "STANDARDS.md" not in line:
            continue
        for anchor in _GOV_ANCHOR_REF_RE.findall(line):
            if anchor not in anchors:
                failures.append(
                    f".agents/expectations/INDEX.md:{lineno}: anchor #{anchor} "
                    "not found in scenarios/STANDARDS.md (C7)"
                )


def gov_role_pointer(root: Path, failures: list[str]) -> None:
    """A2 pointer model: when the suite checkout (with .agents/roles/) is the
    parent of this checkout, this repo's AGENTS.md must route to it.
    Standalone clones without a suite parent skip silently."""
    if not (root.parent / ".agents" / "roles" / "coder.md").is_file():
        return
    agents = root / "AGENTS.md"
    text = agents.read_text(encoding="utf-8") if agents.is_file() else ""
    if ".agents/roles/" not in text:
        failures.append(
            "AGENTS.md: suite role contracts detected at ../.agents/roles/ but "
            "no routing pointer present (A2/C4)"
        )


def gov_checks(
    root: Path,
    failures: list[str],
    *,
    placeholder_files: tuple[str, ...] = (),
    check_roles: bool = False,
    check_expectations: bool = False,
) -> None:
    """C3/C4/C5/C7 entry point; see the block header for the change rule."""
    gov_agents_line_cap(root, failures)
    for rel in placeholder_files:
        gov_no_placeholders(root, rel, failures)
    if check_roles:
        gov_role_contracts(root, failures)
    if check_expectations:
        gov_expectations_mapping(root, failures)
# ── END SHARED GOVERNANCE CHECKS (agent-governance 2026-11-08) ───────────────



